#!/usr/bin/env python3
"""Compile the bundled JSON theme documents through the native Zig compiler.

External JSON uses the identical schema and lowering at runtime. This generated
Zig source removes parsing and file dependencies from the built-in fallback.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ("classic", "archive", "studio", "sleeve", "sleeve-classic")
ENUM_FIELDS = {"kind", "binding", "role", "alignment", "color", "background", "focus", "focus_text", "when", "progress"}


def literal(value, key="", depth=0):
    indent = "    " * depth
    child = "    " * (depth + 1)
    if isinstance(value, dict):
        fields = [child + "." + name + " = " + literal(item, name, depth + 1) + "," for name, item in value.items()]
        return ".{\n" + "\n".join(fields) + "\n" + indent + "}"
    if isinstance(value, list):
        return "&.{\n" + "\n".join(child + literal(item, depth=depth + 1) + "," for item in value) + "\n" + indent + "}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return "." + value if key in ENUM_FIELDS else json.dumps(value, ensure_ascii=False)
    return str(value)


def main():
    documents = [json.loads((ROOT / "src/themes" / f"{family}-{appearance}.json").read_text())
                 for family in FAMILIES for appearance in ("light", "dark")]
    source = '''//! Generated by tools/build_themes.py from the bundled JSON sources.
const theme = @import("runtime_theme.zig");
pub const names = [_][]const u8{ "Classic", "Archive", "Studio", "Sleeve", "Sleeve Classic" };
const documents = [_]theme.Document{
'''
    source += ",\n".join(literal(document) for document in documents) + ",\n"
    source += '''
};
pub const plans = block: {
    @setEvalBranchQuota(20000000);
    var result: [documents.len]theme.Plan = undefined;
    for (documents, &result) |document, *plan| theme.compile(document, plan) catch @compileError("Invalid bundled theme");
    break :block result;
};
'''
    (ROOT / "src/builtin_themes.zig").write_text(source)


if __name__ == "__main__":
    main()
